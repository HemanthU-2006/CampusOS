export const DEPARTMENT_FACULTY_MAP: Record<string, FacultyMember[]> = {
  CSE: CSE_FACULTY,
  ISE: ISE_FACULTY,
  'AI&ML': AIML_FACULTY,
  AIML: AIML_FACULTY,
  'CS-DS': CSDS_FACULTY,
  CSDS: CSDS_FACULTY,
  ECE: ECE_FACULTY,
  EEE: EEE_FACULTY,
  MECH: MECH_FACULTY,
  ME: MECH_FACULTY,
  CIVIL: CIVIL_FACULTY,
  MBA: MBA_FACULTY,
};

export function getFacultyByBranch(branchCode: string): FacultyMember[] {
  const normalized = branchCode.toUpperCase().replace(/\s+/g, '');
  if (DEPARTMENT_FACULTY_MAP[normalized]) {
    return DEPARTMENT_FACULTY_MAP[normalized];
  }
  if (DEPARTMENT_FACULTY_MAP[branchCode]) {
    return DEPARTMENT_FACULTY_MAP[branchCode];
  }
  // Fallback to ISE if branch not matched
  return ISE_FACULTY;
}
